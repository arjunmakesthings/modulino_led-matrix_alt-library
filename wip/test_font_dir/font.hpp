// ------------------------------------------------------------ convenience API

// All lit pixels of one character. This is the "pass a letter, get x,y back"
// entry point:  auto pts = font7x12::pixels('h');
inline std::vector<Point> pixels(uint32_t codepoint, int originX = 0,
                                 int originY = 0) {
    std::vector<Point> out;
    out.reserve(32);
    forEachPixel(codepoint, originX, originY,
                 [&out](int x, int y) { out.push_back(Point{x, y}); });
    return out;
}

// All lit pixels of a whole string, stepping ADVANCE px per character.
inline std::vector<Point> textPixels(const std::string& text, int originX = 0,
                                     int originY = 0, int advance = ADVANCE,
                                     int lineHeight = HEIGHT) {
    std::vector<Point> out;
    out.reserve(text.size() * 32);
    forEachTextPixel(text.c_str(), originX, originY,
                     [&out](int x, int y) { out.push_back(Point{x, y}); },
                     advance, lineHeight);
    return out;
}

// The 12 raw row masks, useful for blitting straight to a framebuffer.
inline std::vector<uint8_t> rows(uint32_t codepoint) {
    const uint8_t* g = glyphOr(codepoint);
    if (!g) return std::vector<uint8_t>(HEIGHT, 0);
    return std::vector<uint8_t>(g, g + HEIGHT);
}


constexpr size_t kExtendedCount = sizeof(kExtended) / sizeof(kExtended[0]);

// ------------------------------------------------------------------- lookup

// Returns a pointer to 12 row bytes, or nullptr if the code point has no
// glyph in this font.
inline const uint8_t* glyph(uint32_t codepoint) {
    if (codepoint >= 0x20 && codepoint <= 0x7E)
        return kAscii[codepoint - 0x20];
    size_t lo = 0, hi = kExtendedCount;
    while (lo < hi) {
        size_t mid = (lo + hi) / 2;
        uint32_t cp = kExtended[mid].cp;
        if (cp == codepoint) return kExtended[mid].rows;
        if (cp < codepoint) lo = mid + 1; else hi = mid;
    }
    return nullptr;
}

// Same, but falls back to '?' for unmapped characters so callers never get
// a null pointer. Pass fallback = 0 to disable the substitution.
inline const uint8_t* glyphOr(uint32_t codepoint, uint32_t fallback = '?') {
    const uint8_t* g = glyph(codepoint);
    if (!g && fallback) g = glyph(fallback);
    return g;
}

inline bool hasGlyph(uint32_t codepoint) { return glyph(codepoint) != nullptr; }

// True if the pixel at (x, y) within the 7x12 cell is lit.
inline bool pixelAt(uint32_t codepoint, int x, int y) {
    if (x < 0 || x >= WIDTH || y < 0 || y >= HEIGHT) return false;
    const uint8_t* g = glyphOr(codepoint);
    return g && (g[y] >> (WIDTH - 1 - x)) & 1;
}

// ------------------------------------------------- zero-allocation traversal

// Calls fn(x, y) for every lit pixel of one character. `fn` can be a lambda,
// function pointer, or any callable -- nothing is allocated.
template <typename F>
inline void forEachPixel(uint32_t codepoint, int originX, int originY, F&& fn) {
    const uint8_t* g = glyphOr(codepoint);
    if (!g) return;
    for (int y = 0; y < HEIGHT; ++y) {
        uint8_t row = g[y];
        if (!row) continue;
        for (int x = 0; x < WIDTH; ++x)
            if ((row >> (WIDTH - 1 - x)) & 1) fn(originX + x, originY + y);
    }
}

template <typename F>
inline void forEachPixel(uint32_t codepoint, F&& fn) {
    forEachPixel(codepoint, 0, 0, static_cast<F&&>(fn));
}

// Walks a null-terminated ASCII/Latin-1 string. '\n' starts a new line.
// Returns the x advance consumed by the longest line.
template <typename F>
inline int forEachTextPixel(const char* text, int originX, int originY, F&& fn,
                            int advance = ADVANCE, int lineHeight = HEIGHT) {
    int x = originX, y = originY, widest = 0;
    for (const char* p = text; *p; ++p) {
        if (*p == '\n') {
            if (x - originX > widest) widest = x - originX;
            x = originX; y += lineHeight;
            continue;
        }
        forEachPixel(static_cast<uint8_t>(*p), x, y, fn);
        x += advance;
    }
    if (x - originX > widest) widest = x - originX;
    return widest;
}

